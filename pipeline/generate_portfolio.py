"""Loan-ly Planet: synthetic agricultural loan portfolio with satellite- and weather-like signals.

Writes web/public/data/portfolio.json. Run:  python3 pipeline/generate_portfolio.py

Everything here is SYNTHETIC. It is shaped like the real thing so the app can be built and demoed before the
Earth Engine pipeline (pipeline/gee_extract.py) is wired up:

  * a fictional lender ("Banco Demo") with ~240 farm loans in the Pampas, Uruguay, southern Brazil and Paraguay
  * the 2022/23 season, which was a severe La Nina drought in this region (the back-test the demo replays)
  * per field, per dekad (10-day period) from 1 Jun 2022 to 31 May 2023:
      ndvi (Sentinel-2 like), rain and its normal (CHIRPS like), tmax and its normal and frost days (ERA5-Land like),
      soil-moisture percentile (SMAP like), flooded fraction (Sentinel-1 like), hail flag
  * 20 past seasons per field (2002/03-2021/22) generated by the same crop model, from which the field's own
    climatology (mean, sd, p10, p90 per dekad) and the analog table (NDVI z-score per dekad -> final yield anomaly) come
  * simulated outcomes (realised yield anomaly, default) used only for the back-test on the Methodology page

The schema matches what gee_extract.py will produce, so swapping synthetic for real data does not touch the app.
"""
import json
import math
from datetime import date, timedelta
from pathlib import Path

import numpy as np

RNG = np.random.default_rng(2023)
OUT = Path(__file__).resolve().parent.parent / "web" / "public" / "data" / "portfolio.json"

START = date(2022, 6, 1)
N = 36  # dekads, Jun 2022 .. May 2023


def dekad_dates():
    out, y, m = [], 2022, 6
    for _ in range(12):
        for d in (1, 11, 21):
            out.append(date(y, m, d))
        m += 1
        if m == 13:
            y, m = y + 1, 1
    return out


DEK = dekad_dates()
MONTH = np.array([d.month for d in DEK])

# ----------------------------------------------------------------------------------------------- crops
# sow: typical sowing dekad index (0 = 1 Jun), dur: dekads sowing -> harvest, win: stress window (dekads after sowing)
CROPS = {
    "soy":       dict(label="Soybean", sow=17, dur=15, win=(7, 11), win_label="Flowering & pod fill", cost=430, yld=3.1, price=520, color="#2e9d5b"),
    "maize":     dict(label="Maize", sow=12, dur=16, win=(7, 10), win_label="Silking & early grain fill", cost=690, yld=8.2, price=240, color="#e0a21b"),
    "wheat":     dict(label="Wheat", sow=1, dur=17, win=(11, 14), win_label="Heading & flowering", cost=380, yld=3.2, price=300, color="#b5793a"),
    "sunflower": dict(label="Sunflower", sow=11, dur=13, win=(6, 9), win_label="Flowering", cost=360, yld=2.2, price=480, color="#f26b1d"),
}

# ----------------------------------------------------------------------------------------------- regions
# sev: how hard the 2022/23 drought hit (0..1); hist: how strongly past dry years hit this region; crops: weights
REGIONS = [
    dict(id="AR-SF", country="Argentina", name="Santa Fe · Centro", lat=-31.45, lng=-61.25, sev=0.95, hist=1.0, crops=dict(soy=.5, maize=.25, wheat=.2, sunflower=.05), n=34),
    dict(id="AR-BN", country="Argentina", name="Buenos Aires · Norte", lat=-33.85, lng=-60.55, sev=0.90, hist=0.9, crops=dict(soy=.5, maize=.3, wheat=.2), n=36),
    dict(id="AR-ER", country="Argentina", name="Entre Ríos · Paraná", lat=-31.95, lng=-59.95, sev=0.85, hist=0.9, crops=dict(soy=.5, maize=.2, wheat=.3), n=22),
    dict(id="AR-CS", country="Argentina", name="Córdoba · Sur", lat=-33.15, lng=-64.10, sev=0.80, hist=1.0, crops=dict(soy=.45, maize=.35, wheat=.15, sunflower=.05), n=30),
    dict(id="AR-LP", country="Argentina", name="La Pampa · Este", lat=-35.65, lng=-63.75, sev=0.65, hist=1.1, crops=dict(sunflower=.3, maize=.3, wheat=.3, soy=.1), n=18),
    dict(id="AR-BS", country="Argentina", name="Buenos Aires · Sudeste", lat=-37.30, lng=-59.10, sev=0.40, hist=0.8, crops=dict(wheat=.4, sunflower=.3, soy=.2, maize=.1), n=24),
    dict(id="AR-SA", country="Argentina", name="Salta · Este", lat=-24.90, lng=-64.10, sev=0.25, hist=0.8, crops=dict(soy=.6, maize=.4), n=12),
    dict(id="UY-SO", country="Uruguay", name="Soriano", lat=-33.45, lng=-57.75, sev=0.70, hist=0.8, crops=dict(soy=.6, wheat=.3, maize=.1), n=22),
    dict(id="BR-RS", country="Brazil", name="Rio Grande do Sul · Missões", lat=-28.30, lng=-54.30, sev=0.75, hist=0.9, crops=dict(soy=.7, maize=.2, wheat=.1), n=26),
    dict(id="PY-IT", country="Paraguay", name="Itapúa", lat=-26.90, lng=-55.90, sev=0.35, hist=0.7, crops=dict(soy=.7, maize=.2, wheat=.1), n=16),
]

# 2022/23 drought profile through the season (fraction of normal rain missing at full severity)
PROFILE_2223 = np.interp(np.arange(N), [0, 6, 9, 12, 15, 18, 21, 24, 27, 30, 35], [0.25, 0.35, 0.55, 0.65, 0.65, 0.7, 0.8, 0.75, 0.45, 0.15, 0.05])
# heat waves: mid-Dec 2022 and Jan 2023 (dekads 19-23) and early Mar 2023 (dekad 27)
HEAT_2223 = np.zeros(N); HEAT_2223[[19, 20, 21, 22, 23, 27]] = [2.5, 3.5, 4.5, 3.0, 2.0, 2.5]
# late frosts Sep-Oct 2022 (dekads 10-14)
FROST_2223 = np.zeros(N); FROST_2223[[10, 11, 12, 13]] = [2, 3, 2, 1]

# past seasons 2002/03 .. 2021/22 and how dry each was across the region (synthetic, loosely modeled on the known dry years)
HIST_YEARS = list(range(2002, 2022))
HIST_SEV = {2002: -.2, 2003: .15, 2004: -.1, 2005: .2, 2006: -.25, 2007: .1, 2008: .8, 2009: -.3, 2010: .1, 2011: .55, 2012: -.25,
            2013: .05, 2014: -.15, 2015: -.2, 2016: .1, 2017: .7, 2018: -.1, 2019: .3, 2020: .35, 2021: .45}

NAMES = ["La Esperanza", "El Ombú", "Los Talas", "San José", "La Carolina", "Las Acacias", "El Trébol", "Santa Rita", "La Aurora", "Los Cardos",
         "La Celina", "El Mirador", "Las Lomas", "San Martín", "La Querencia", "El Recreo", "Los Paraísos", "Santa Elena", "La Margarita", "El Porvenir",
         "Don Bosco", "La Blanqueada", "Los Molles", "El Chañar", "La Rinconada", "San Pedro", "Las Rosas", "El Sauce", "La Victoria", "Tres Lagunas"]
PREFIX = ["Estancia", "Agropecuaria", "Establecimiento", "Campo", "Granja", "Cooperativa"]
SUFFIX = {"Argentina": ["S.A.", "S.R.L.", "S.A.S.", ""], "Uruguay": ["S.A.", "Ltda.", ""], "Brazil": ["Ltda.", "S.A.", ""], "Paraguay": ["S.A.", "S.R.L.", ""]}


def rain_normal(lat):
    # wet summer, dry winter; drier to the south-west
    base = 6 + 34 * (0.5 + 0.5 * np.cos((MONTH - 1) / 12 * 2 * np.pi)) + 6 * np.sin((MONTH - 3) / 12 * 2 * np.pi)
    return np.clip(base * (1 + (lat + 33) * -0.03), 4, 70)


def tmax_normal(lat):
    return 24 + 8 * np.cos((MONTH - 1) / 12 * 2 * np.pi) + (-(lat + 33)) * -0.4 * 1.0


def ndvi_curve(sow, dur, crop):
    """Unstressed NDVI by dekad for a crop sown at dekad `sow`."""
    t = np.arange(N) - sow
    up = 1 / (1 + np.exp(-(t - dur * 0.28) / 1.1))
    down = 1 / (1 + np.exp((t - dur * 0.82) / 1.0))
    amp = dict(soy=.62, maize=.66, wheat=.55, sunflower=.5)[crop]
    v = 0.22 + amp * up * down
    v[t < 0] = 0.24 + 0.03 * np.sin(np.arange(N)[t < 0])  # fallow / stubble before sowing
    return v


def season(sow, dur, win, crop, rain, rnorm, heat, frost, irrigated, hail_at=None, rng=RNG):
    """Run the toy crop model for one season. Returns ndvi, soil-moisture percentile, stress index S, yield loss fraction."""
    deficit = np.clip(1 - rain / rnorm, -1, 1)
    if irrigated:
        deficit = deficit * 0.3
    w = np.zeros(N); s = np.zeros(N)
    for i in range(N):
        w[i] = (0.72 * w[i - 1] if i else 0) + 0.28 * deficit[i]
    sm = np.clip(50 - 75 * w + rng.normal(0, 4, N), 1, 99)
    t = np.arange(N) - sow
    for i in range(N):
        on = 0 <= t[i] <= dur
        heat_x = max(0, heat[i] - 1.5) * 0.06 * (0 if irrigated else 1)
        frost_x = frost[i] * 0.05 if crop == "wheat" and win[0] - 2 <= t[i] <= win[1] else 0
        x = max(0, w[i]) * 0.9 + heat_x + frost_x
        s[i] = max(0.85 * s[i - 1] if i else 0, x) if on else 0
    ndvi = ndvi_curve(sow, dur, crop) * (1 - 0.6 * np.clip(s, 0, 1)) + rng.normal(0, 0.012, N)
    if hail_at is not None:
        ndvi[hail_at:hail_at + 4] -= np.array([0.22, 0.16, 0.1, 0.05])[: max(0, min(4, N - hail_at))]
    win_idx = [i for i in range(N) if win[0] <= t[i] <= win[1]]
    sw = s[win_idx].mean() if win_idx else 0
    loss = np.clip(0.75 * sw ** 1.3 + 0.12 * s[(t >= 0) & (t <= dur)].mean() - 0.04 + rng.normal(0, 0.05), -0.15, 0.95)
    if hail_at is not None and 0 <= hail_at - sow <= dur:
        loss = min(0.95, loss + 0.25)
    return np.clip(ndvi, 0.05, 0.95), sm, s, loss


def rect(lat, lng, ha, rng):
    """A rotated rectangle of roughly `ha` hectares as a [lng, lat] ring."""
    a = math.sqrt(ha * 1e4 * rng.uniform(1.3, 2.6))
    b = ha * 1e4 / a
    th = rng.uniform(0, math.pi)
    pts = []
    for dx, dy in ((-a / 2, -b / 2), (a / 2, -b / 2), (a / 2, b / 2), (-a / 2, b / 2), (-a / 2, -b / 2)):
        x = dx * math.cos(th) - dy * math.sin(th)
        y = dx * math.sin(th) + dy * math.cos(th)
        pts.append([round(lng + x / (111320 * math.cos(math.radians(lat))), 5), round(lat + y / 110540, 5)])
    return pts


def r(a, d=3):
    return [None if (x is None or not np.isfinite(x)) else round(float(x), d) for x in a]


def main():
    loans, k = [], 0
    for reg in REGIONS:
        crops, w = zip(*reg["crops"].items())
        w = np.array(w) / sum(w)
        rnorm = rain_normal(reg["lat"])
        tnorm = tmax_normal(reg["lat"])
        for j in range(reg["n"]):
            k += 1
            rng = np.random.default_rng(1000 + k)
            crop = str(rng.choice(crops, p=w)); c = CROPS[crop]
            lat = reg["lat"] + rng.normal(0, 0.45); lng = reg["lng"] + rng.normal(0, 0.55)
            sow = int(np.clip(c["sow"] + rng.integers(-2, 3), 0, N - c["dur"] - 1))
            dur, win = c["dur"], c["win"]
            area = float(np.round(rng.lognormal(math.log(320), 0.6)))
            area = float(np.clip(area, 40, 2500))
            irrigated = bool(rng.random() < 0.05)
            sev = float(np.clip(reg["sev"] + rng.normal(0, 0.12), 0, 1.1))

            # --- history: 20 past seasons of the same field, for climatology and analogs
            H = []
            for y in HIST_YEARS:
                hs = HIST_SEV[y] * reg["hist"] + rng.normal(0, 0.12)
                prof = np.clip(hs * np.interp(np.arange(N), [0, 12, 21, 30, 35], [0.6, 0.9, 1, 0.6, 0.3]) + rng.normal(0, 0.18, N), -1.2, 0.95)
                hrain = rnorm * (1 - prof)
                hheat = np.clip(rng.normal(max(0, hs) * 1.5, 1.0, N), 0, None)
                hfrost = np.clip(np.round(rng.normal(0.6, 0.8, N)), 0, None) * (MONTH >= 9) * (MONTH <= 10)
                hsow = int(np.clip(sow + rng.integers(-1, 2), 0, N - dur - 1))
                nd, _, _, loss = season(hsow, dur, win, crop, hrain, rnorm, hheat, hfrost, irrigated, rng=rng)
                H.append((nd, -loss))
            Hn = np.array([h[0] for h in H]); Hy = np.array([h[1] for h in H])
            mean, sd = Hn.mean(0), np.maximum(Hn.std(0), 0.025)
            p10, p90 = np.percentile(Hn, 10, 0), np.percentile(Hn, 90, 0)
            hz = (Hn - mean) / sd

            # --- this season (2022/23)
            rain = np.clip(rnorm * (1 - sev * PROFILE_2223 + rng.normal(0, 0.22, N)), 0, None)
            heat = np.clip(HEAT_2223 * (0.6 + 0.6 * sev) + rng.normal(0, 0.6, N), -2, None)
            tmax = tnorm + heat
            frost = np.clip(np.round(FROST_2223 * (1 if reg["lat"] < -32 else 0.4) * rng.uniform(0.5, 1.4) + rng.normal(0, 0.4, N)), 0, None)
            hail_at = None
            if rng.random() < 0.06:
                hail_at = int(sow + rng.integers(4, dur - 3))
            ndvi, sm, S, loss = season(sow, dur, win, crop, rain, rnorm, heat, frost, irrigated, hail_at, rng=rng)
            flood = np.zeros(N)
            if reg["id"] in ("AR-ER", "BR-RS") and rng.random() < 0.06:  # a few low fields flooded after the March storms
                f0 = int(rng.integers(27, 31)); flood[f0:f0 + 2] = rng.uniform(0.2, 0.6)
                ndvi[f0:f0 + 3] -= 0.12
            hail = np.zeros(N, dtype=int)
            if hail_at is not None:
                hail[hail_at] = 1

            # --- loan terms
            cost = c["cost"] * rng.uniform(0.6, 1.1)
            amount = float(np.round(area * cost, -3))
            harvest = sow + dur
            orig = DEK[max(0, sow - 3)]
            mat_i = min(N - 1, harvest + int(rng.integers(2, 5)))
            maturity = DEK[mat_i] + timedelta(days=9)
            installments = rng.random() < 0.35
            repay = ([dict(date=str(DEK[max(0, sow + 6)]), usd=round(amount * 0.3)), dict(date=str(maturity), usd=round(amount * 0.7))]
                     if installments else [dict(date=str(maturity), usd=amount)])
            coll = str(rng.choice(["land mortgage", "crop pledge", "warrant on grain", "unsecured"], p=[.3, .4, .15, .15]))
            lgd = dict({"land mortgage": .28, "crop pledge": .45, "warrant on grain": .38, "unsecured": .62})[coll] + rng.normal(0, .03)
            rating = int(rng.choice([2, 3, 4, 5, 6], p=[.12, .3, .32, .18, .08]))
            pd12 = float(dict({2: .008, 3: .015, 4: .028, 5: .05, 6: .09})[rating] * rng.uniform(0.8, 1.25))
            ins_r = rng.random()
            insurance = (dict(type="hail & fire (indemnity)", perils=["hail"], coverPct=round(float(rng.uniform(.6, .9)), 2)) if ins_r < 0.38 else
                         dict(type="parametric drought (index)", perils=["drought"], coverPct=round(float(rng.uniform(.4, .7)), 2), trigger=55) if ins_r < 0.46 else None)
            farm = float(np.round(area * rng.uniform(1, 3.5)))
            other = int(rng.choice([0, 0, 1, 1, 2, 3]))
            exp_y = c["yld"] * rng.uniform(0.85, 1.15) * (1.1 if irrigated else 1)
            yrs = list(range(2013, 2023))
            yields = [round(float(exp_y * (1 + Hy[HIST_YEARS.index(y - 1)]) * (0.97 + 0.006 * (y - 2013))), 2) for y in yrs]

            # --- simulated outcome (back-test only): default more likely when the season failed and margins were thin
            rev = area * exp_y * (1 - max(0, loss)) * c["price"]
            cover = rev / max(1, amount * 1.12)
            p_def = 1 / (1 + math.exp(-(math.log(pd12 / (1 - pd12)) + 4.5 * max(0, loss - 0.15) + 1.5 * max(0, 1 - cover))))
            if insurance and "drought" in insurance["perils"] and loss > 0.3:
                p_def *= 0.45
            defaulted = bool(rng.random() < p_def)

            cc = reg["country"]
            name = f"{rng.choice(PREFIX)} {rng.choice(NAMES)} {rng.choice(SUFFIX[cc])}".strip()
            loans.append(dict(
                id=f"{reg['id']}-{j + 1:03d}", borrower=name, country=cc, region=reg["name"], regionId=reg["id"],
                lat=round(lat, 4), lng=round(lng, 4), ring=rect(lat, lng, area, rng), crop=crop, sow=sow, harvest=harvest,
                window=[sow + win[0], sow + win[1]], areaHa=area, farmHa=farm, irrigated=irrigated,
                amountUsd=amount, originated=str(orig), maturity=str(maturity), repay=repay, rating=rating, pd12=round(pd12, 4),
                lgd=round(float(np.clip(lgd, .15, .8)), 3), collateral=coll, insurance=insurance, otherLoans=other,
                expYield=round(float(exp_y), 2), price=c["price"],
                ndvi=r(ndvi), clim=dict(mean=r(mean), sd=r(sd), p10=r(p10), p90=r(p90)),
                rain=r(rain, 1), rainNormal=r(rnorm, 1), tmax=r(tmax, 1), tmaxNormal=r(tnorm, 1), frost=[int(x) for x in frost],
                sm=r(sm, 0), flood=r(flood, 2), hail=hail.tolist(),
                hist=dict(z=[r(row, 2) for row in hz], yieldAnom=r(Hy, 3)),
                yields=dict(years=yrs, tha=yields),
                outcome=dict(yieldAnom=round(float(-loss), 3), defaulted=defaulted),
            ))

    meta = dict(
        lender="Banco Demo (fictional)", season="2022/23", synthetic=True,
        dekads=[str(d) for d in DEK], asOfDefault=DEK.index(date(2023, 1, 21)),
        crops={k: dict(label=v["label"], color=v["color"], window=v["win_label"], price=v["price"]) for k, v in CROPS.items()},
        regions=[dict(id=x["id"], name=x["name"], country=x["country"], lat=x["lat"], lng=x["lng"]) for x in REGIONS],
        histYears=HIST_YEARS,
        note="Synthetic portfolio shaped like Sentinel-2 / CHIRPS / ERA5-Land / SMAP / Sentinel-1 signals; replays the 2022/23 La Niña drought.",
    )
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(dict(meta=meta, loans=loans), separators=(",", ":"), ensure_ascii=False))
    print(f"{len(loans)} loans -> {OUT} ({OUT.stat().st_size / 1e6:.1f} MB); defaults {sum(l['outcome']['defaulted'] for l in loans)}")


if __name__ == "__main__":
    main()
